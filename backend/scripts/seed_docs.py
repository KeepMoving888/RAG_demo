async def _write_seed_files() -> int:
    """将种子文档写入 data/seed/documents/ 目录, 返回写入文件数."""
    _DOCS_DIR.mkdir(parents=True, exist_ok=True)
    count = 0
    for doc in _SEED_DOCUMENTS:
        path = _DOCS_DIR / doc["file_name"]
        path.write_text(doc["content"], encoding="utf-8")
        count += 1
    logger.info("种子文档已写入文件系统: {} 篇 -> {}", count, _DOCS_DIR)
    return count


async def _seed_documents_to_db() -> tuple[int, int]:
    """将种子文档写入 DB 并提交解析, 返回 (新增数, 跳过数)."""
    added = 0
    skipped = 0
    pipeline = DocumentPipeline()

    async with AsyncSessionLocal() as session:
        # 预加载部门
        dept_result = await session.execute(select(Department))
        dept_map = {d.code: d for d in dept_result.scalars().all()}

        for doc_data in _SEED_DOCUMENTS:
            # 计算 MD5 (内容)
            import hashlib
            md5 = hashlib.md5(doc_data["content"].encode("utf-8")).hexdigest()

            # 去重
            exist = await session.execute(
                select(Document).where(Document.md5_hash == md5)
            )
            if exist.scalar_one_or_none() is not None:
                skipped += 1
                continue

            dept = dept_map.get(doc_data["department_code"])
            file_path = _DOCS_DIR / doc_data["file_name"]

            doc = Document(
                title=doc_data["title"],
                file_name=doc_data["file_name"],
                file_path=str(file_path),
                file_size=len(doc_data["content"].encode("utf-8")),
                file_format="md" if doc_data["file_name"].endswith(".md") else "txt",
                mime_type="text/markdown" if doc_data["file_name"].endswith(".md") else "text/plain",
                md5_hash=md5,
                department_id=dept.id if dept else None,
                category=doc_data["category"],
                status="pending",
                uploaded_by=None,
            )
            session.add(doc)
            await session.flush()
            added += 1

            # 提交解析任务 (失败不阻断)
            try:
                await pipeline.submit(doc.id)
            except Exception as exc:  # noqa: BLE001
                logger.warning("提交解析任务失败 doc_id={}: {}", doc.id, str(exc))

        await session.commit()

    logger.info("种子文档入库完成: 新增 {} 篇, 跳过 {} 篇", added, skipped)
    return added, skipped


async def _write_terminology() -> int:
    """写入术语词典."""
    _SEED_DIR.mkdir(parents=True, exist_ok=True)
    _TERMS_FILE.write_text(
        json.dumps(_TERMINOLOGY, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    logger.info("术语词典已写入: {} 条 -> {}", len(_TERMINOLOGY), _TERMS_FILE)
    return len(_TERMINOLOGY)


async def _write_eval_dataset() -> int:
    """写入 RAG 评估数据集."""
    _SEED_DIR.mkdir(parents=True, exist_ok=True)
    _EVAL_FILE.write_text(
        json.dumps(_EVAL_DATASET, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    logger.info("评估数据集已写入: {} 条 -> {}", len(_EVAL_DATASET), _EVAL_FILE)
    return len(_EVAL_DATASET)


async def main() -> None:
    """主流程: 写文件 -> 入库 -> 术语 -> 评估集 -> 打印统计."""
    logger.info("=" * 60)
    logger.info("开始灌入种子数据...")
    logger.info("=" * 60)

    files_written = await _write_seed_files()
    added, skipped = await _seed_documents_to_db()
    terms = await _write_terminology()
    eval_samples = await _write_eval_dataset()

    logger.info("=" * 60)
    logger.info("种子数据灌入完成:")
    logger.info("  - 文件写入: {} 篇", files_written)
    logger.info("  - 文档入库: 新增 {} 篇, 跳过 (已存在) {} 篇", added, skipped)
    logger.info("  - 术语词典: {} 条", terms)
    logger.info("  - 评估数据集: {} 条", eval_samples)
    logger.info("=" * 60)

    await engine.dispose()


if __name__ == "__main__":
    asyncio.run(main())
